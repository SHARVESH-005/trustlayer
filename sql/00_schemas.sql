-- Schemas for TrustLayer. Safe to re-run.
CREATE SCHEMA IF NOT EXISTS RAW;
CREATE SCHEMA IF NOT EXISTS CURATED;
CREATE SCHEMA IF NOT EXISTS TRUSTLAYER;

-- Raw yellow taxi trips, one row per trip, plus load metadata.
CREATE TABLE IF NOT EXISTS RAW.YELLOW_TRIPS (
    VENDORID              DECIMAL(5,0),
    TPEP_PICKUP_DATETIME  TIMESTAMP,
    TPEP_DROPOFF_DATETIME TIMESTAMP,
    PASSENGER_COUNT       DECIMAL(5,0),
    TRIP_DISTANCE         DOUBLE,
    RATECODEID            DECIMAL(5,0),
    STORE_AND_FWD_FLAG    VARCHAR(1),
    PULOCATIONID          DECIMAL(5,0),
    DOLOCATIONID          DECIMAL(5,0),
    PAYMENT_TYPE          DECIMAL(5,0),
    FARE_AMOUNT           DOUBLE,
    EXTRA                 DOUBLE,
    MTA_TAX               DOUBLE,
    TIP_AMOUNT            DOUBLE,
    TOLLS_AMOUNT          DOUBLE,
    IMPROVEMENT_SURCHARGE DOUBLE,
    TOTAL_AMOUNT          DOUBLE,
    CONGESTION_SURCHARGE  DOUBLE,
    AIRPORT_FEE           DOUBLE,
    LOAD_ID               VARCHAR(64),
    LOADED_AT             TIMESTAMP
);

-- One row per ingest run; the checks read this for freshness and volume.
CREATE TABLE IF NOT EXISTS TRUSTLAYER.LOAD_LOG (
    LOAD_ID      VARCHAR(64),
    TABLE_NAME   VARCHAR(128),
    SOURCE_URL   VARCHAR(256),
    ROW_COUNT    DECIMAL(18,0),
    STATUS       VARCHAR(16),
    STARTED_AT   TIMESTAMP,
    FINISHED_AT  TIMESTAMP,
    MESSAGE      VARCHAR(2000)
);

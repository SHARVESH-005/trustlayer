-- Business-facing views that dashboards read. They only ever see CURATED data,
-- so a quarantined batch never reaches them.
CREATE OR REPLACE VIEW MART.DAILY_REVENUE AS
SELECT TRUNC(TPEP_PICKUP_DATETIME) AS TRIP_DATE,
       COUNT(*)                    AS TRIPS,
       SUM(TOTAL_AMOUNT)           AS REVENUE,
       AVG(TIP_AMOUNT)             AS AVG_TIP
FROM CURATED.YELLOW_TRIPS
GROUP BY TRUNC(TPEP_PICKUP_DATETIME);

-- Built on another view, so lineage shows a two-step chain.
CREATE OR REPLACE VIEW MART.EXEC_KPIS AS
SELECT TRIP_DATE,
       TRIPS,
       REVENUE,
       REVENUE / NULLIF(TRIPS, 0) AS REVENUE_PER_TRIP
FROM MART.DAILY_REVENUE;

-- 1 = Newark, 132 = JFK, 138 = LaGuardia (TLC taxi zone ids).
CREATE OR REPLACE VIEW MART.AIRPORT_DEMAND AS
SELECT TRUNC(TPEP_PICKUP_DATETIME, 'HH') AS HOUR_START,
       PULOCATIONID                      AS AIRPORT_ZONE,
       COUNT(*)                          AS TRIPS,
       AVG(TOTAL_AMOUNT)                 AS AVG_FARE
FROM CURATED.YELLOW_TRIPS
WHERE PULOCATIONID IN (1, 132, 138)
GROUP BY TRUNC(TPEP_PICKUP_DATETIME, 'HH'), PULOCATIONID;

CREATE OR REPLACE VIEW MART.PAYMENT_MIX AS
SELECT PAYMENT_TYPE,
       COUNT(*)          AS TRIPS,
       SUM(TOTAL_AMOUNT) AS REVENUE,
       AVG(TIP_AMOUNT)   AS AVG_TIP
FROM CURATED.YELLOW_TRIPS
GROUP BY PAYMENT_TYPE;
